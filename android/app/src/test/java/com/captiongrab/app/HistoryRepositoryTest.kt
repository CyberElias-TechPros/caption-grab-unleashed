package com.captiongrab.app

import com.captiongrab.app.data.HistoryEntry
import com.captiongrab.app.data.HistoryRepository
import com.captiongrab.app.data.Transcript
import com.captiongrab.app.data.TranscriptSegment
import java.io.File
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.ExperimentalCoroutinesApi
import kotlinx.coroutines.test.runTest
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder

@OptIn(ExperimentalCoroutinesApi::class)
class HistoryRepositoryTest {

    @get:Rule
    val tmp = TemporaryFolder()

    private lateinit var dir: File

    @Before
    fun setUp() {
        dir = tmp.newFolder("library")
    }

    private fun transcript(
        id: String = "dQw4w9WgXcQ",
        language: String = "en",
        title: String = "A talk",
        lines: Int = 3,
    ) = Transcript(
        videoId = id,
        title = title,
        author = "Channel",
        language = language,
        languageName = language.uppercase(),
        isAutoGenerated = true,
        segments = (1..lines).map { TranscriptSegment(it.toDouble(), 1.0, "line $it of $title") },
        text = (1..lines).joinToString(" ") { "line $it of $title" },
    )

    private fun repo(clock: () -> Long = { 1_000L }) =
        HistoryRepository(dir, Dispatchers.Unconfined, clock)

    @Test
    fun `saves and reloads an entry`() = runTest {
        val repository = repo()
        repository.load()
        repository.save(transcript(), "https://img/1.jpg", limit = 10)

        val reloaded = repo()
        reloaded.load()

        assertEquals(1, reloaded.entries.value.size)
        val entry = reloaded.entries.value.first()
        assertEquals("dQw4w9WgXcQ", entry.videoId)
        assertEquals(3, entry.segmentCount)
        assertEquals(3, entry.toTranscript().segments.size)
        assertEquals("line 1 of A talk line 2 of A talk line 3 of A talk", entry.toTranscript().text)
    }

    @Test
    fun `deduplicates the same video and language`() = runTest {
        var now = 1_000L
        val repository = repo { now }
        repository.load()
        repository.save(transcript(title = "first"), "t", limit = 10)
        now += 1000
        repository.save(transcript(title = "second"), "t", limit = 10)

        assertEquals(1, repository.entries.value.size)
        assertEquals("second", repository.entries.value.first().title)
    }

    @Test
    fun `keeps different languages separately`() = runTest {
        val repository = repo()
        repository.load()
        repository.save(transcript(language = "en"), "t", limit = 10)
        repository.save(transcript(language = "es"), "t", limit = 10)
        assertEquals(2, repository.entries.value.size)
    }

    @Test
    fun `enforces the retention limit and drops oldest first`() = runTest {
        var now = 1_000L
        val repository = repo { now }
        repository.load()
        repeat(5) { index ->
            now += 1000
            repository.save(transcript(id = "video00000$index", title = "talk $index"), "t", limit = 3)
        }
        assertEquals(3, repository.entries.value.size)
        // Newest first.
        assertEquals("talk 4", repository.entries.value.first().title)
        assertEquals("talk 2", repository.entries.value.last().title)
    }

    @Test
    fun `pinned entries survive the retention limit`() = runTest {
        var now = 1_000L
        val repository = repo { now }
        repository.load()
        now += 1000
        repository.save(transcript(id = "pinnedvid01", title = "keeper"), "t", limit = 2)
        val keeper = repository.entries.value.first()
        repository.setPinned(keeper.id, true)

        repeat(3) { index ->
            now += 1000
            repository.save(transcript(id = "othervideo$index", title = "other $index"), "t", limit = 2)
        }
        assertTrue(repository.entries.value.any { it.title == "keeper" })
        assertTrue(repository.entries.value.first().pinned)
        assertEquals(2, repository.entries.value.size)
    }

    @Test
    fun `clearUnpinned keeps starred captures`() = runTest {
        val repository = repo()
        repository.load()
        repository.save(transcript(id = "starred12345", title = "starred"), "t", limit = 10)
        repository.save(transcript(id = "plain1234567", title = "plain"), "t", limit = 10)
        repository.setPinned(repository.entries.value.first { it.title == "starred" }.id, true)

        repository.clearUnpinned()

        assertEquals(1, repository.entries.value.size)
        assertEquals("starred", repository.entries.value.first().title)
    }

    @Test
    fun `deletes entries and rewrites the index`() = runTest {
        val repository = repo()
        repository.load()
        repository.save(transcript(), "t", limit = 10)
        val id = repository.entries.value.first().id
        repository.delete(id)

        assertTrue(repository.entries.value.isEmpty())
        val reloaded = repo()
        reloaded.load()
        assertTrue(reloaded.entries.value.isEmpty())
    }

    @Test
    fun `search matches titles channels and transcript bodies`() = runTest {
        val repository = repo()
        repository.load()
        repository.save(transcript(id = "aaa11111111", title = "Kotlin coroutines"), "t", limit = 10)
        repository.save(transcript(id = "bbb22222222", title = "Design systems"), "t", limit = 10)

        assertEquals(1, repository.search("coroutines").size)
        assertEquals(2, repository.search("CHANNEL").size) // both entries share a channel
        assertEquals(2, repository.search("line 1").size)
        assertEquals(2, repository.search("").size)
    }

    @Test
    fun `corrupt index degrades to an empty library instead of crashing`() = runTest {
        dir.mkdirs()
        File(dir, "index.json").writeText("{ this is not json")
        val repository = repo()
        repository.load()
        assertTrue(repository.entries.value.isEmpty())
    }

    @Test
    fun `thumbnails round trip through disk`() = runTest {
        val repository = repo()
        repository.load()
        repository.cacheThumbnail("dQw4w9WgXcQ", byteArrayOf(1, 2, 3, 4))
        val bytes = repository.thumbnail("dQw4w9WgXcQ")
        assertNotNull(bytes)
        assertEquals(4, bytes!!.size)
        assertNull(repository.thumbnail("missingvideo"))
    }

    @Test
    fun `importEntry respects the limit`() = runTest {
        val repository = repo()
        repository.load()
        val entry = HistoryEntry.from(transcript(), "t", now = 5_000L)
        repository.importEntry(entry, limit = 1)
        assertEquals(1, repository.entries.value.size)
        repository.importEntry(entry.copy(id = "different"), limit = 1)
        assertEquals(1, repository.entries.value.size)
    }

    @Test
    fun `history entry rebuilds full text from segments`() {
        val longTranscript = transcript(lines = 200)
        val entry = HistoryEntry.from(longTranscript, "t")
        val restored = entry.toTranscript()
        assertFalse(restored.text.isBlank())
        assertEquals(longTranscript.text, restored.text)
    }
}
