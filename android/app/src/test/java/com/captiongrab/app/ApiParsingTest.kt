package com.captiongrab.app

import com.captiongrab.app.data.ApiError
import com.captiongrab.app.data.CaptionApi
import com.captiongrab.app.data.Transcript
import com.captiongrab.app.data.VideoInfo
import com.captiongrab.app.data.YouTubeUrl
import kotlinx.coroutines.test.runTest
import kotlinx.serialization.json.Json
import okhttp3.HttpUrl
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Protocol
import okhttp3.Response
import okhttp3.ResponseBody.Companion.toResponseBody
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * API-contract tests against the exact JSON the Worker emits.
 * A fake OkHttp interceptor stands in for the network, so these run offline.
 */
class ApiParsingTest {

    private val json = Json { ignoreUnknownKeys = true; isLenient = true; explicitNulls = false }

    private class FakeCall(
        private val handler: (HttpUrl) -> Pair<Int, String>,
    ) : okhttp3.Interceptor {
        var lastUrl: HttpUrl? = null
        var lastHeaders: okhttp3.Headers? = null

        override fun intercept(chain: okhttp3.Interceptor.Chain): Response {
            lastUrl = chain.request().url
            lastHeaders = chain.request().headers
            val (status, body) = handler(chain.request().url)
            return Response.Builder()
                .request(chain.request())
                .protocol(Protocol.HTTP_2)
                .code(status)
                .message("OK")
                .body(body.toResponseBody("application/json".toMediaType()))
                .build()
        }
    }

    private fun api(handler: (HttpUrl) -> Pair<Int, String>): Pair<CaptionApi, FakeCall> {
        val fake = FakeCall(handler)
        val client = OkHttpClient.Builder().addInterceptor(fake).build()
        return CaptionApi("https://api.test", client) to fake
    }

    private val videoJson = """
        {
          "videoId": "dQw4w9WgXcQ",
          "title": "A talk about captions",
          "author": "Channel",
          "lengthSeconds": 754,
          "viewCount": 1234567,
          "thumbnail": "https://i.ytimg.com/vi/dQw4w9WgXcQ/hqdefault.jpg",
          "captionsAvailable": true,
          "tracks": [
            {"languageCode": "en", "languageName": "English", "kind": "manual", "translatable": true},
            {"languageCode": "es", "languageName": "Spanish", "kind": "auto", "translatable": true}
          ]
        }
    """.trimIndent()

    private val transcriptJson = """
        {
          "videoId": "dQw4w9WgXcQ",
          "title": "A talk about captions",
          "author": "Channel",
          "requestedLanguage": "en",
          "language": "es",
          "languageName": "Spanish",
          "sourceLanguage": "en",
          "sourceLanguageName": "English",
          "isAutoGenerated": true,
          "translated": true,
          "segments": [
            {"start": 0.5, "dur": 2.25, "text": "Hola a todos"},
            {"start": 2.75, "dur": 1.5, "text": "bienvenidos"}
          ],
          "text": "Hola a todos bienvenidos"
        }
    """.trimIndent()

    @Test
    fun `video info decodes the worker contract`() {
        val video = json.decodeFromString<VideoInfo>(videoJson)
        assertEquals("dQw4w9WgXcQ", video.videoId)
        assertEquals(754.0, video.lengthSeconds, 0.001)
        assertEquals(1_234_567L, video.viewCount)
        assertEquals(2, video.tracks.size)
        assertTrue(video.tracks.first().isAutoGenerated.not())
        assertTrue(video.tracks[1].isAutoGenerated)
        assertTrue(video.captionsAvailable)
    }

    @Test
    fun `transcript decodes translations and segments`() {
        val transcript = json.decodeFromString<Transcript>(transcriptJson)
        assertEquals("es", transcript.language)
        assertEquals("en", transcript.sourceLanguage)
        assertTrue(transcript.translated)
        assertTrue(transcript.isAutoGenerated)
        assertEquals(2, transcript.segments.size)
        assertEquals(4.25, transcript.durationSeconds, 0.001)
        assertEquals(4, transcript.words)
    }

    @Test
    fun `missing optional fields fall back safely`() {
        val minimal = json.decodeFromString<Transcript>(
            """{"videoId":"dQw4w9WgXcQ","segments":[{"start":0,"text":"hi"}]}""",
        )
        assertEquals("en", minimal.language)
        assertEquals(0.0, minimal.segments.first().dur, 0.001)
        assertFalse(minimal.translated)
    }

    @Test
    fun `video request hits the right path with the id`() = runTest {
        val (service, fake) = api { 200 to videoJson }
        val video = service.videoInfo("dQw4w9WgXcQ")
        assertEquals("dQw4w9WgXcQ", video.videoId)
        val url = fake.lastUrl!!
        assertEquals("/api/video", url.encodedPath)
        assertEquals("dQw4w9WgXcQ", url.queryParameter("id"))
        assertEquals("application/json", fake.lastHeaders!!["accept"])
    }

    @Test
    fun `transcript request forwards language and translate flag`() = runTest {
        val (service, fake) = api { 200 to transcriptJson }
        service.transcript("dQw4w9WgXcQ", "es", allowTranslate = false)
        val url = fake.lastUrl!!
        assertEquals("/api/transcript", url.encodedPath)
        assertEquals("es", url.queryParameter("lang"))
        assertEquals("0", url.queryParameter("translate"))

        service.transcript("dQw4w9WgXcQ", "es", allowTranslate = true)
        assertEquals("1", fake.lastUrl!!.queryParameter("translate"))
    }

    @Test
    fun `worker error codes map to actionable failures`() = runTest {
        val (service, _) = api {
            404 to """{"error":{"code":"NO_CAPTIONS","message":"This video has no caption tracks."}}"""
        }
        val error = runCatching { service.transcript("dQw4w9WgXcQ", "en", true) }.exceptionOrNull()
        assertTrue(error is ApiError)
        error as ApiError
        assertEquals(ApiError.Code.NO_CAPTIONS, error.code)
        assertEquals("This video has no caption tracks.", error.message)
        assertEquals("No captions on this video", error.title)
        assertFalse(error.isRetryable)
    }

    @Test
    fun `language unavailable surfaces the available tracks`() = runTest {
        val (service, _) = api {
            404 to """
                {"error":{"code":"LANGUAGE_UNAVAILABLE","message":"No fr captions.",
                 "details":{"availableLanguages":["en","es","de"]}}}
            """.trimIndent()
        }
        val error = runCatching { service.transcript("dQw4w9WgXcQ", "fr", false) }.exceptionOrNull() as ApiError
        assertEquals(ApiError.Code.LANGUAGE_UNAVAILABLE, error.code)
        assertEquals(listOf("en", "es", "de"), error.availableLanguages)
        assertTrue(error.suggestion.contains("en"))
    }

    @Test
    fun `rate limiting reports the retry window`() = runTest {
        val (service, _) = api {
            429 to """{"error":{"code":"RATE_LIMITED","message":"Too many requests. Please wait 42s and try again."}}"""
        }
        val error = runCatching { service.videoInfo("dQw4w9WgXcQ") }.exceptionOrNull() as ApiError
        assertEquals(ApiError.Code.RATE_LIMITED, error.code)
        assertEquals(42, error.retryAfterSeconds)
        assertTrue(error.isRetryable)
    }

    @Test
    fun `invalid ids never reach the network`() = runTest {
        var called = false
        val (service, _) = api { called = true; 200 to videoJson }
        val error = runCatching { service.videoInfo("short") }.exceptionOrNull() as ApiError
        assertEquals(ApiError.Code.INVALID_VIDEO_ID, error.code)
        assertFalse(called)
    }

    @Test
    fun `malformed json becomes a parse error, not a crash`() = runTest {
        val (service, _) = api { 200 to "not json at all" }
        val error = runCatching { service.videoInfo("dQw4w9WgXcQ") }.exceptionOrNull() as ApiError
        assertEquals(ApiError.Code.PARSE_ERROR, error.code)
    }

    @Test
    fun `health probe reports reachability`() = runTest {
        val (service, _) = api { 200 to """{"ok":true,"service":"captiongrab-api"}""" }
        val health = service.health(force = true)
        assertTrue(health.reachable)
        assertFalse(health.degraded)
    }

    @Test
    fun `health probe degrades quietly when offline`() = runTest {
        val (service, _) = api { throw java.io.IOException("offline") }
        val health = service.health(force = true)
        assertFalse(health.reachable)
    }

    @Test
    fun `api base url joins paths without doubling slashes`() {
        val client = OkHttpClient()
        val fake = FakeCall { 200 to videoJson }
        val withSlash = CaptionApi("https://api.test/", client.newBuilder().addInterceptor(fake).build())
        runTest { withSlash.videoInfo("dQw4w9WgXcQ") }
        assertEquals("https://api.test/api/video", fake.lastUrl!!.toString().substringBefore("?"))
    }

    @Test
    fun `error copy stays human for every code`() {
        ApiError.Code.entries.forEach { code ->
            val error = ApiError(code, "")
            assertTrue("missing title for $code", error.title.isNotBlank())
            assertTrue("missing suggestion for $code", error.suggestion.isNotBlank())
        }
    }

    @Test
    fun `platform guard rejects non youtube input before calling the api`() {
        assertEquals(null, YouTubeUrl.extractVideoId("https://vimeo.com/1"))
        assertEquals("dQw4w9WgXcQ", YouTubeUrl.extractVideoId("https://youtu.be/dQw4w9WgXcQ"))
    }
}
