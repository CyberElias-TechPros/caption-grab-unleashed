package com.captiongrab.app.ui.screens

import androidx.compose.foundation.background
import androidx.compose.foundation.clickable
import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.Row
import androidx.compose.foundation.layout.Spacer
import androidx.compose.foundation.layout.fillMaxWidth
import androidx.compose.foundation.layout.padding
import androidx.compose.foundation.layout.size
import androidx.compose.foundation.layout.width
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.rounded.CheckCircle
import androidx.compose.material.icons.rounded.Language
import androidx.compose.material.icons.rounded.Translate
import androidx.compose.material3.Icon
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp
import com.captiongrab.app.data.CaptionTrack
import com.captiongrab.app.ui.components.Tag
import com.captiongrab.app.ui.theme.CaptionTheme

/** One selectable caption track. Used by the in-reader language sheet. */
@Composable
fun TrackRow(
    track: CaptionTrack,
    selected: Boolean,
    onClick: () -> Unit,
) {
    val c = CaptionTheme.colors
    Row(
        Modifier
            .fillMaxWidth()
            .padding(vertical = 2.dp)
            .clip(RoundedCornerShape(14.dp))
            .background(if (selected) c.primary.copy(alpha = 0.12f) else Color.Transparent)
            .clickable(onClick = onClick)
            .padding(horizontal = 12.dp, vertical = 12.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Icon(
            if (track.translatable) Icons.Rounded.Translate else Icons.Rounded.Language,
            contentDescription = null,
            tint = if (selected) c.primary else c.textMuted,
            modifier = Modifier.size(17.dp),
        )
        Spacer(Modifier.width(11.dp))
        Column(Modifier.weight(1f)) {
            Text(
                track.languageName.ifBlank { track.languageCode },
                style = MaterialTheme.typography.titleMedium,
                color = c.text,
            )
            Spacer(Modifier.width(2.dp))
            Row {
                Text(
                    track.languageCode,
                    style = MaterialTheme.typography.bodySmall,
                    color = c.textMuted,
                )
                Spacer(Modifier.width(6.dp))
                Tag(
                    if (track.isAutoGenerated) "auto" else "creator",
                    color = if (track.isAutoGenerated) c.amber else c.green,
                )
                if (track.translatable) {
                    Spacer(Modifier.width(6.dp))
                    Tag("translatable", color = c.cyan)
                }
            }
        }
        if (selected) {
            Icon(
                Icons.Rounded.CheckCircle,
                contentDescription = "Current track",
                tint = c.primary,
                modifier = Modifier.size(19.dp),
            )
        }
    }
}
