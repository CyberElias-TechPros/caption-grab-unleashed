package com.captiongrab.app.data

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * Wire + storage models. These mirror the CaptionGrab Worker API contract
 * (`worker/src/index.ts`) exactly and are also what gets persisted locally.
 *
 * Everything is `@Serializable` so the same classes are used for network JSON
 * and for the on-device history file — one shape, no mapping bugs.
 */

@Serializable
data class TranscriptSegment(
    val start: Double,
    val dur: Double = 0.0,
    val text: String,
) {
    val end: Double get() = start + if (dur > 0) dur else 2.0
}

@Serializable
enum class TrackKind {
    @SerialName("manual") MANUAL,
    @SerialName("auto") AUTO,
}

@Serializable
data class CaptionTrack(
    val languageCode: String,
    val languageName: String = languageCode,
    val kind: TrackKind = TrackKind.AUTO,
    val translatable: Boolean = false,
) {
    val isAutoGenerated: Boolean get() = kind == TrackKind.AUTO
}

@Serializable
data class VideoInfo(
    val videoId: String,
    val title: String = "",
    val author: String = "",
    val lengthSeconds: Double = 0.0,
    val viewCount: Long? = null,
    val thumbnail: String = "",
    val captionsAvailable: Boolean = true,
    val tracks: List<CaptionTrack> = emptyList(),
    val demo: Boolean = false,
)

@Serializable
data class Transcript(
    val videoId: String,
    val title: String = "",
    val author: String = "",
    val requestedLanguage: String = "en",
    val language: String = "en",
    val languageName: String = "English",
    val sourceLanguage: String? = null,
    val sourceLanguageName: String? = null,
    val isAutoGenerated: Boolean = false,
    val translated: Boolean = false,
    val segments: List<TranscriptSegment> = emptyList(),
    val text: String = "",
    val demo: Boolean = false,
) {
    val words: Int get() = TranscriptFormat.countWords(text.ifBlank { TranscriptFormat.plainText(segments) })
    val durationSeconds: Double get() = segments.lastOrNull()?.end ?: 0.0
}

/**
 * A locally stored extraction. `segments` is always complete; `text` is
 * rebuilt on restore so long transcripts are never truncated.
 */
@Serializable
data class HistoryEntry(
    val id: String,
    val videoId: String,
    val title: String,
    val author: String,
    val thumbnail: String,
    val language: String,
    val languageName: String,
    val translated: Boolean,
    val isAutoGenerated: Boolean,
    val wordCount: Int,
    val segmentCount: Int,
    val createdAt: Long,
    val segments: List<TranscriptSegment>,
    val sourceLanguageName: String? = null,
    /** Starred captures sort first and survive "clear unpinned". */
    val pinned: Boolean = false,
    /** Last time the user opened this capture. */
    val openedAt: Long = 0L,
) {
    fun toTranscript(): Transcript = Transcript(
        videoId = videoId,
        title = title,
        author = author,
        requestedLanguage = language,
        language = language,
        languageName = languageName,
        sourceLanguageName = sourceLanguageName,
        isAutoGenerated = isAutoGenerated,
        translated = translated,
        segments = segments,
        text = TranscriptFormat.plainText(segments),
    )

    companion object {
        fun from(transcript: Transcript, thumbnail: String, now: Long = System.currentTimeMillis()): HistoryEntry =
            HistoryEntry(
                id = "${transcript.videoId}:${transcript.language}:$now",
                videoId = transcript.videoId,
                title = transcript.title,
                author = transcript.author,
                thumbnail = thumbnail,
                language = transcript.language,
                languageName = transcript.languageName,
                translated = transcript.translated,
                isAutoGenerated = transcript.isAutoGenerated,
                wordCount = transcript.words,
                segmentCount = transcript.segments.size,
                createdAt = now,
                segments = transcript.segments,
                sourceLanguageName = transcript.sourceLanguageName,
            )
    }
}
