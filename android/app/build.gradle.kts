/**
 * API base URL.
 *
 * Resolution order (first non-blank wins):
 *  1. `api.base.url` in `local.properties` (developer override, never committed)
 *  2. `CAPTIONGRAB_API_URL` environment variable (CI / Gradle command line)
 *  3. the production Worker default below
 */
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
val apiBaseUrl: String =
    (localProps.getProperty("api.base.url")
        ?: System.getenv("CAPTIONGRAB_API_URL")
        ?: "https://captiongrab-api.cyber-e54.workers.dev")
        .trim()
        .trimEnd('/')

